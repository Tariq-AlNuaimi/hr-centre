// Style Dictionary config (A5 / cat 21 — token-pipeline seed).
//
// Compiles tokens/design-tokens.json into CSS custom properties. This is a
// PARALLEL, additive artifact: app/tokens.css remains the hand-authored source
// of truth the app actually imports; this pipeline proves the tokens.json ->
// platform-output path works so a fork that later needs multi-platform tokens
// (JS objects, iOS/Android, a Figma sync) extends THIS config instead of
// hand-maintaining N copies of the ruler.
//
// Values pass through verbatim (no size/rem or color normalization transforms
// are triggered — the source tokens carry no `type`, so `4px`/`#4f46e5` land
// in the output exactly as written), which keeps the generated file a faithful
// mirror of the primitive :root block in app/tokens.css.
//
// Run: `npm run tokens:build` (-> scripts/build-tokens.mjs).
const config = {
  source: ["tokens/design-tokens.json"],
  platforms: {
    css: {
      transformGroup: "css",
      buildPath: "tokens/build/",
      files: [
        {
          destination: "tokens.generated.css",
          format: "css/variables",
          options: {
            // Emit a leading banner so nobody edits the generated file by hand.
            fileHeader: () => [
              "DO NOT EDIT — generated by `npm run tokens:build`",
              "Source: tokens/design-tokens.json (Style Dictionary).",
              "Hand-authored source of truth: app/tokens.css.",
            ],
          },
        },
      ],
    },
  },
};

export default config;
