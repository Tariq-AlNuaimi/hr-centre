"use client";

import * as React from "react";
import * as SelectPrimitive from "@radix-ui/react-select";
import { cn } from "@/lib/utils";

/**
 * Select — shadcn/ui-style select on @radix-ui/react-select (ADR-029,
 * Workstream C3). Radix owns the hard parts: full keyboard navigation
 * (type-ahead, arrows, Home/End), `aria-*` listbox wiring, focus return, and
 * collision-aware positioning. Styled on the semantic surface tokens so dark
 * mode is the single [data-theme="dark"] variable swap. Trigger compensates for
 * Preflight-off (appearance-none) like the other native-element primitives.
 * Replaces AntD `<Select>` on the migrated filter/form screens.
 */

export const Select = SelectPrimitive.Root;
export const SelectGroup = SelectPrimitive.Group;
export const SelectValue = SelectPrimitive.Value;

export const SelectTrigger = React.forwardRef<
  React.ComponentRef<typeof SelectPrimitive.Trigger>,
  React.ComponentPropsWithoutRef<typeof SelectPrimitive.Trigger>
>(({ className, children, ...props }, ref) => (
  <SelectPrimitive.Trigger
    ref={ref}
    className={cn(
      "appearance-none inline-flex h-9 w-full items-center justify-between gap-2 rounded-md border border-input bg-background px-3 py-1 text-sm text-foreground shadow-sm outline-none transition-colors data-[placeholder]:text-muted-foreground focus-visible:ring-2 focus-visible:ring-ring disabled:cursor-not-allowed disabled:opacity-50 [&>span]:truncate",
      className,
    )}
    {...props}
  >
    {children}
    <SelectPrimitive.Icon asChild>
      <svg
        aria-hidden
        viewBox="0 0 24 24"
        className="h-4 w-4 flex-none opacity-60"
        fill="none"
        stroke="currentColor"
        strokeWidth={2}
        strokeLinecap="round"
        strokeLinejoin="round"
      >
        <path d="m6 9 6 6 6-6" />
      </svg>
    </SelectPrimitive.Icon>
  </SelectPrimitive.Trigger>
));
SelectTrigger.displayName = SelectPrimitive.Trigger.displayName;

